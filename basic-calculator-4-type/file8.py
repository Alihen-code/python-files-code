a = int(input('Enter a number: '))
b = int(input('Enter a second number: '))
total_add = a + b
print(f'The sum of {a} and {b} is {total_add}.')
print('-------------------------------')

total_sub = a - b
print(f'The difference between {a} and {b} is {total_sub}.')

print('-------------------------------')
total_multiply = a * b
print(f'The product of {a} and {b} is {total_multiply}.')

print('-------------------------------')
total_divide = a / b
print(f'The quotient of {a} and {b} is {total_divide}.')